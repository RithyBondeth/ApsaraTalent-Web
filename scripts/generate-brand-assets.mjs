// Render every platform asset from the checked-in, approved AT vector masters.
// Usage: node scripts/generate-brand-assets.mjs --mobile-root ../ApsaraTalent-Mobile
import sharp from "sharp";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const mobileArg = process.argv.indexOf("--mobile-root");
if (mobileArg >= 0 && !process.argv[mobileArg + 1]) {
  throw new Error("--mobile-root requires the Flutter project path.");
}
const mobile =
  mobileArg < 0
    ? null
    : path.resolve(process.cwd(), process.argv[mobileArg + 1]);
const masters = path.join(root, "assets/utils");
// The UI palette is the source of truth for exported brand colours.
const stylesheet = await readFile(path.join(root, "app/globals.css"), "utf8");
function primaryColor(selector) {
  const token = stylesheet.match(
    new RegExp(
      `${selector}\\s*\\{[\\s\\S]*?--primary:\\s*([\\d.]+)\\s+([\\d.]+)%\\s+([\\d.]+)%`,
    ),
  );
  if (!token) throw new Error(`Missing ${selector} primary colour token.`);
  const hue = Number(token[1]) / 30;
  const saturation = Number(token[2]) / 100;
  const lightness = Number(token[3]) / 100;
  const amplitude = saturation * Math.min(lightness, 1 - lightness);
  const channel = (offset) => {
    const k = (offset + hue) % 12;
    return Math.round(
      255 * (lightness - amplitude * Math.max(-1, Math.min(k - 3, 9 - k, 1))),
    )
      .toString(16)
      .padStart(2, "0");
  };
  return `#${channel(0)}${channel(8)}${channel(4)}`.toUpperCase();
}
const blue = primaryColor(":root");
const darkBlue = primaryColor("\\.dark");
const recolorMark = (svg, color) =>
  svg.replace(/(<path\b[^>]*\bfill=")[^"]+("\s)/, `$1${color}$2`);
const symbol = recolorMark(
  await readFile(path.join(masters, "logo-at-symbol.svg"), "utf8"),
  blue,
);
const darkSymbol = recolorMark(symbol, darkBlue);
const light = recolorMark(
  await readFile(path.join(masters, "logo-at-light.svg"), "utf8"),
  blue,
);
const dark = recolorMark(
  await readFile(path.join(masters, "logo-at-dark.svg"), "utf8"),
  darkBlue,
);
const getSize = (svg) =>
  svg
    .match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/)
    .slice(1)
    .map(Number);
const [symbolWidth, symbolHeight] = getSize(symbol);
const [lockupWidth, lockupHeight] = getSize(light);
const contents = (svg) =>
  svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<title>[^<]*<\/title>/, "")
    .replace(/<\/svg>\s*$/, "");
const symbolPath = symbol.match(/ d="([^"]+)"/)[1];
let written = 0;

async function save(filename, buffer) {
  await mkdir(path.dirname(filename), { recursive: true });
  await writeFile(filename, buffer);
  written++;
}

async function png(svg, width) {
  return sharp(Buffer.from(svg), { density: 288 })
    .resize({ width })
    .png()
    .toBuffer();
}

function squareSvg(size, coverage = 0.76, background = "#FFFFFF") {
  const scale = (size * coverage) / symbolWidth;
  const x = (size - symbolWidth * scale) / 2;
  const y = (size - symbolHeight * scale) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" fill="${background}"/><g transform="translate(${x} ${y}) scale(${scale})">${contents(symbol)}</g></svg>`;
}

async function icon(filename, size, coverage = 0.76) {
  const buffer = await png(squareSvg(size, coverage), size);
  await save(filename, await sharp(buffer).removeAlpha().png().toBuffer());
}

// Transparent in-app artwork, byte-identical on web and Flutter.
for (const [filename, svg] of [
  ["logo-at-symbol.svg", symbol],
  ["logo-at-symbol-dark.svg", darkSymbol],
  ["logo-at-light.svg", light],
  ["logo-at-dark.svg", dark],
])
  await save(path.join(masters, filename), svg);
await save(
  path.join(root, "utils/constants/brand-dimensions.constant.ts"),
  `// Generated by scripts/generate-brand-assets.mjs.\nexport const BRAND_LOCKUP_ASPECT_RATIO = ${lockupWidth} / ${lockupHeight};\nexport const BRAND_SYMBOL_ASPECT_RATIO = ${symbolWidth} / ${symbolHeight};\n`,
);
for (const [filename, svg, width] of [
  ["logo-for-lightmode.png", light, lockupWidth * 2],
  ["logo-for-darkmode.png", dark, lockupWidth * 2],
  ["logo-without-text.png", symbol, symbolWidth * 2],
  ["logo-without-text-darkmode.png", darkSymbol, symbolWidth * 2],
]) {
  const buffer = await png(svg, width);
  await save(path.join(masters, filename), buffer);
  if (mobile) await save(path.join(mobile, "assets/logo", filename), buffer);
}

// Next file conventions also supply browser icons and social share artwork.
await icon(path.join(root, "app/icon.png"), 512, 0.82);
await icon(path.join(root, "app/apple-icon.png"), 180);
const scale = 950 / lockupWidth;
const social = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630"><rect width="1200" height="630" fill="#FFFFFF"/><g transform="translate(125 ${(630 - lockupHeight * scale) / 2}) scale(${scale})">${contents(light)}</g></svg>`;
const socialBuffer = await png(social, 1200);
await save(path.join(root, "app/opengraph-image.png"), socialBuffer);
await save(path.join(root, "app/twitter-image.png"), socialBuffer);

// PNG-compressed ICO entries keep browser and Windows icons crisp at each size.
async function ico() {
  const sizes = [16, 32, 48, 64, 128, 256];
  const images = await Promise.all(
    sizes.map((size) => png(squareSvg(size, 0.82), size)),
  );
  const directory = Buffer.alloc(6 + 16 * sizes.length);
  directory.writeUInt16LE(1, 2);
  directory.writeUInt16LE(sizes.length, 4);
  let offset = directory.length;
  sizes.forEach((size, index) => {
    const entry = 6 + index * 16;
    directory[entry] = directory[entry + 1] = size === 256 ? 0 : size;
    directory.writeUInt16LE(1, entry + 4);
    directory.writeUInt16LE(32, entry + 6);
    directory.writeUInt32LE(images[index].length, entry + 8);
    directory.writeUInt32LE(offset, entry + 12);
    offset += images[index].length;
  });
  return Buffer.concat([directory, ...images]);
}
const favicon = await ico();
await save(path.join(root, "app/favicon.ico"), favicon);

if (mobile) {
  await save(
    path.join(mobile, "lib/core/constants/brand_dimensions.dart"),
    `// Generated by ApsaraTalent-Web/scripts/generate-brand-assets.mjs.\nconst double brandLockupAspectRatio = ${lockupWidth} / ${lockupHeight};\nconst double brandSymbolAspectRatio = ${symbolWidth} / ${symbolHeight};\n`,
  );

  const android = path.join(mobile, "android/app/src/main/res");
  for (const [density, size] of Object.entries({
    mdpi: 48,
    hdpi: 72,
    xhdpi: 96,
    xxhdpi: 144,
    xxxhdpi: 192,
  })) {
    await icon(path.join(android, `mipmap-${density}/ic_launcher.png`), size);
  }
  function vector(size, coverage, color = blue) {
    const scale = (size * coverage) / symbolWidth;
    const x = (size - symbolWidth * scale) / 2;
    const y = (size - symbolHeight * scale) / 2;
    return `<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="${size}dp" android:height="${size}dp" android:viewportWidth="${size}" android:viewportHeight="${size}"><group android:translateX="${x}" android:translateY="${y}" android:scaleX="${scale}" android:scaleY="${scale}"><path android:fillColor="${color}" android:fillType="evenOdd" android:pathData="${symbolPath}"/></group></vector>\n`;
  }
  // The full foreground fits Android's 66dp safe circle after masking.
  await save(
    path.join(android, "drawable/ic_launcher_foreground.xml"),
    vector(108, 0.5),
  );
  await save(
    path.join(android, "drawable/ic_launcher_monochrome.xml"),
    vector(108, 0.5, "#000000"),
  );
  await save(
    path.join(android, "drawable/ic_stat_apsara.xml"),
    vector(24, 0.82, "#FFFFFF"),
  );
  await save(path.join(android, "drawable/splash_mark.xml"), vector(160, 0.76));
  await save(
    path.join(android, "drawable-night/splash_mark.xml"),
    vector(160, 0.76, darkBlue),
  );
  await save(
    path.join(android, "values/brand_colors.xml"),
    '<?xml version="1.0" encoding="utf-8"?>\n<resources><color name="ic_launcher_background">#FFFFFF</color></resources>\n',
  );
  for (const version of [26, 33]) {
    const monochrome =
      version === 33
        ? '\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />'
        : "";
    await save(
      path.join(android, `mipmap-anydpi-v${version}/ic_launcher.xml`),
      `<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/ic_launcher_background" />\n    <foreground android:drawable="@drawable/ic_launcher_foreground" />${monochrome}\n</adaptive-icon>\n`,
    );
  }

  for (const platform of ["ios", "macos"]) {
    const folder = path.join(
      mobile,
      platform,
      "Runner/Assets.xcassets/AppIcon.appiconset",
    );
    const catalog = JSON.parse(
      await readFile(path.join(folder, "Contents.json"), "utf8"),
    );
    const entries = new Map(
      catalog.images.map((image) => [
        image.filename,
        Math.round(parseFloat(image.size) * parseFloat(image.scale)),
      ]),
    );
    for (const [filename, size] of entries)
      await icon(path.join(folder, filename), size);
  }
  const launch = path.join(
    mobile,
    "ios/Runner/Assets.xcassets/LaunchImage.imageset",
  );
  for (const [filename, multiplier] of [
    ["LaunchImage.png", 1],
    ["LaunchImage@2x.png", 2],
    ["LaunchImage@3x.png", 3],
  ]) {
    // A 160pt transparent launch mark, with the same shape as the Flutter splash.
    await save(
      path.join(launch, filename),
      await png(symbol, 160 * multiplier),
    );
  }
  await icon(path.join(mobile, "web/favicon.png"), 32, 0.82);
  for (const size of [192, 512]) {
    await icon(path.join(mobile, `web/icons/Icon-${size}.png`), size);
    await icon(
      path.join(mobile, `web/icons/Icon-maskable-${size}.png`),
      size,
      0.6,
    );
  }
  await save(
    path.join(mobile, "windows/runner/resources/app_icon.ico"),
    favicon,
  );
  const manifestPath = path.join(mobile, "web/manifest.json");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  manifest.theme_color = blue;
  await save(manifestPath, `${JSON.stringify(manifest, null, 4)}\n`);
}
console.log(
  `Generated ${written} brand assets. Lockup ${lockupWidth}:${lockupHeight}; symbol ${symbolWidth}:${symbolHeight}.`,
);
